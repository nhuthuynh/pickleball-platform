// Apply must find its target by POSITION. Two if-statements with the same
// condition text would otherwise both be rewritten, or the wrong one would be.
func TestApplyTargetsByPositionNotByText(t *testing.T) {
	const twin = `package p

func F(a int) int {
	if a > 0 {
		return 1
	}
	if a > 0 {
		return 2
	}
	return 0
}
`
	// Target the SECOND of two identical conditions.
	muts, err := Mutants("p.go", []byte(twin), map[int]bool{7: true})
	if err != nil {
		t.Fatal(err)
	}
	if len(muts) != 2 {
		t.Fatalf("got %d mutants, want 2", len(muts))
	}
	for _, m := range muts {
		out, err := Apply([]byte(twin), m)
		if err != nil {
			t.Fatal(err)
		}
		lines := strings.Split(string(out), "\n")
		if !strings.Contains(lines[3], "a > 0") {
			t.Errorf("%s: the FIRST if (line 4) was rewritten; target was line 7:\n%s", m.Kind, out)
		}
		if strings.Contains(lines[6], "a > 0") {
			t.Errorf("%s: the SECOND if (line 7) was not rewritten:\n%s", m.Kind, out)
		}
	}
}

// The parse-error branches in Mutants and Apply were survivors on this
// package's own first mutation-pin run: no test fed either of them source
// that does not parse. Found by the tool, on itself, in the commit that
// introduced it.
func TestMutantsAndApplyRefuseUnparseableSource(t *testing.T) {
	bad := []byte("package p\n\nfunc F( {\n")
	if _, err := Mutants("p.go", bad, map[int]bool{3: true}); err == nil {
		t.Error("Mutants returned nil error for source that does not parse")
	}
	m := Mutation{File: "p.go", Line: 3, Kind: AlwaysFalse, Cond: "x"}
	if _, err := Apply(bad, m); err == nil {
		t.Error("Apply returned nil error for source that does not parse")
	}
}

