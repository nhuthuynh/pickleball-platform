const sample = `package p

func F(a, b int) int {
	if a > b {
		return a
	}
	if a == 0 {
		return -1
	}
	return b
}
`

func TestMutantsOnlyCoversAddedLines(t *testing.T) {
	tests := []struct {
		name  string
		added map[int]bool
		want  int // number of mutants
	}{
		// Two mutants per if-statement: always-false and always-true.
		{"first if only", map[int]bool{4: true}, 2},
		{"both ifs", map[int]bool{4: true, 7: true}, 4},
		{"a line with no if", map[int]bool{5: true}, 0},
		{"nothing added", map[int]bool{}, 0},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := Mutants("p.go", []byte(sample), tt.added)
			if err != nil {
				t.Fatal(err)
			}
			if len(got) != tt.want {
				t.Errorf("got %d mutants, want %d: %+v", len(got), tt.want, got)
			}
		})
	}
}

func TestMutantsRecordTheConditionAndBothDirections(t *testing.T) {
	got, err := Mutants("p.go", []byte(sample), map[int]bool{4: true})
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 2 {
		t.Fatalf("got %d mutants, want 2", len(got))
	}
	kinds := map[string]bool{}
	for _, m := range got {
		kinds[m.Kind] = true
		if m.Line != 4 {
			t.Errorf("Line = %d, want 4", m.Line)
		}
		if m.Cond != "a > b" {
			t.Errorf("Cond = %q, want %q", m.Cond, "a > b")
		}
	}
	if !kinds[AlwaysFalse] || !kinds[AlwaysTrue] {
		t.Errorf("want both %q and %q, got %v", AlwaysFalse, AlwaysTrue, kinds)
	}
}

func TestApplyReplacesOnlyTheTargetCondition(t *testing.T) {
	muts, err := Mutants("p.go", []byte(sample), map[int]bool{4: true, 7: true})
	if err != nil {
		t.Fatal(err)
	}
	for _, m := range muts {
		out, err := Apply([]byte(sample), m)
		if err != nil {
			t.Fatalf("%v: %v", m, err)
		}
		s := string(out)
		want := "if false {"
		other := "a == 0"
		if m.Kind == AlwaysTrue {
			want = "if true {"
		}
		if !strings.Contains(s, want) {
			t.Errorf("%s at line %d: result does not contain %q:\n%s", m.Kind, m.Line, want, s)
		}
		// The other if-statement must be untouched.
		if m.Line == 4 && !strings.Contains(s, other) {
			t.Errorf("mutating line 4 also changed the if on line 7:\n%s", s)
		}
		// Exactly one condition replaced, never both.
		if strings.Count(s, "if false {")+strings.Count(s, "if true {") != 1 {
			t.Errorf("%s at line %d: more than one condition replaced:\n%s", m.Kind, m.Line, s)
		}
	}
}

