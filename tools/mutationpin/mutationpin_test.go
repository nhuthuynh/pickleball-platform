func TestReportDistinguishesTheThreeOutcomes(t *testing.T) {
	tests := []struct {
		name    string
		results []Result
		want    []string
		absent  []string
	}{
		{
			name:    "no mutants at all",
			results: nil,
			want:    []string{"OK", "no `if` guard"},
		},
		{
			name:    "every mutant killed",
			results: []Result{{Mutation: Mutation{File: "a.go", Line: 4, Kind: AlwaysFalse, Cond: "x"}, Survived: false}},
			want:    []string{"OK", "killed by a test"},
			absent:  []string{"SURVIVED"},
		},
		{
			name: "a survivor",
			results: []Result{
				{Mutation: Mutation{File: "a.go", Line: 4, Kind: AlwaysFalse, Cond: "x > 0"}, Survived: true},
				{Mutation: Mutation{File: "a.go", Line: 4, Kind: AlwaysTrue, Cond: "x > 0"}, Survived: false},
			},
			want: []string{"SURVIVED", "a.go:4", "x > 0", "Advisory", "1 of 2"},
		},
		{
			name:    "a mutant that could not be evaluated",
			results: []Result{{Mutation: Mutation{File: "a.go", Line: 4, Kind: AlwaysTrue, Cond: "x"}, Note: "boom"}},
			want:    []string{"could not be evaluated", "boom"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			out := Report(tt.results)
			for _, w := range tt.want {
				if !strings.Contains(out, w) {
					t.Errorf("report missing %q:\n%s", w, out)
				}
			}
			for _, a := range tt.absent {
				if strings.Contains(out, a) {
					t.Errorf("report should not contain %q:\n%s", a, out)
				}
			}
		})
	}
}

