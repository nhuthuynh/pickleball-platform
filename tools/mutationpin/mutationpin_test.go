func TestMutantsSkipsFilesItMustNotMutate(t *testing.T) {
	generated := "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage p\n"
	tests := []struct {
		name string
		file string
		src  string
		want bool
	}{
		{"a test file, by suffix", "internal/booking/app/service_test.go", sample, true},
		{"generated, inside internal/gen", "internal/gen/bookingdb/models.go", generated, true},

		// Recognition is by Go's own header, NEVER by path. internal/gen as a
		// hardcoded prefix would be the start of the exclusion list that
		// tools/gatecoverage and tools/stalecitations both say must not exist
		// -- and it would miss generated code written anywhere else.
		{"generated, outside internal/gen", "internal/whatever/x.go", generated, true},
		{"a hand-written file under internal/gen", "internal/gen/notes.go", sample, false},

		{"an ordinary source file", "internal/booking/app/service.go", sample, false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := Skip(tt.file, []byte(tt.src)); got != tt.want {
				t.Errorf("Skip(%q) = %v, want %v", tt.file, got, tt.want)
			}
		})
	}
}

func TestParseAddedLines(t *testing.T) {
	// git diff --unified=0 hunk headers: @@ -old,n +new,n @@
	diff := `diff --git a/a.go b/a.go
--- a/a.go
+++ b/a.go
@@ -10,0 +11,2 @@ func F() {
+	if x {
+	}
@@ -20,1 +22,1 @@ func G() {
-	old()
+	if y {
@@ -30,2 +33,0 @@ func H() {
-	gone()
-	alsoGone()
diff --git a/deleted_only.go b/deleted_only.go
--- a/deleted_only.go
+++ b/deleted_only.go
@@ -5,3 +4,0 @@ func Gone() {
-	a()
-	b()
-	c()
diff --git a/b_test.go b/b_test.go
--- a/b_test.go
+++ b/b_test.go
@@ -1,0 +2,1 @@
+	something
`
	got := ParseAddedLines(diff)
	// b_test.go is absent by design: mutating the tests that do the killing
	// is meaningless, so test files never reach the mutant generator.
	if len(got) != 1 {
		t.Fatalf("got %d files, want 1 (b_test.go must be excluded): %v", len(got), got)
	}
	if _, ok := got["b_test.go"]; ok {
		t.Error("b_test.go was included; test files must be excluded")
	}
	// A file whose only hunk is a pure deletion (+N,0) adds no lines, so it
	// must not appear at all -- not even as an empty entry. Without the
	// count == 0 guard it appears with an empty set, which this pins.
	if _, ok := got["deleted_only.go"]; ok {
		t.Errorf("deleted_only.go was included; a pure-deletion hunk adds nothing: %v", got)
	}
	a := got["a.go"]
	for _, want := range []int{11, 12, 22} {
		if !a[want] {
			t.Errorf("a.go: line %d not marked added; got %v", want, a)
		}
	}
	if len(a) != 3 {
		t.Errorf("a.go: got %d added lines, want 3: %v", len(a), a)
	}
}

func tmpRepo(t *testing.T, rel, body string) string {
	t.Helper()
	root := t.TempDir()
	p := filepath.Join(root, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
	return root
}

func TestRunClassifiesSurvivorsAndKills(t *testing.T) {
	tests := []struct {
		name         string
		passed       bool // what the fake test run reports
		wantSurvived bool
	}{
		{"tests pass with the guard removed: the guard is unpinned", true, true},
		{"tests fail with the guard removed: something pins it", false, false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := tmpRepo(t, "pkg/a.go", sample)
			added := map[string]map[int]bool{"pkg/a.go": {4: true}}
			got, err := Run(root, added, func(string) (bool, error) { return tt.passed, nil })
			if err != nil {
				t.Fatal(err)
			}
			if len(got) != 2 {
				t.Fatalf("got %d results, want 2", len(got))
			}
			for _, r := range got {
				if r.Survived != tt.wantSurvived {
					t.Errorf("%s: Survived = %v, want %v", r.Kind, r.Survived, tt.wantSurvived)
				}
			}
		})
	}
}

// The property that matters most. A tool that can leave a mutated source file
// on disk is worse than no tool: every later command silently tests the
// mutant. Restoration must survive a passing run, a failing run, and a runner
// that returns an error.
func TestRunAlwaysRestoresTheFile(t *testing.T) {
	runners := map[string]TestRunner{
		"runner reports pass":  func(string) (bool, error) { return true, nil },
		"runner reports fail":  func(string) (bool, error) { return false, nil },
		"runner returns error": func(string) (bool, error) { return false, errors.New("go test exploded") },
	}
	for name, run := range runners {
		t.Run(name, func(t *testing.T) {
			root := tmpRepo(t, "pkg/a.go", sample)
			if _, err := Run(root, map[string]map[int]bool{"pkg/a.go": {4: true, 7: true}}, run); err != nil {
				t.Fatal(err)
			}
			after, err := os.ReadFile(filepath.Join(root, "pkg/a.go"))
			if err != nil {
				t.Fatal(err)
			}
			if string(after) != sample {
				t.Errorf("file was not restored:\n--- got ---\n%s\n--- want ---\n%s", after, sample)
			}
		})
	}
}

func TestRunPassesTheOwningPackageDirectory(t *testing.T) {
	root := tmpRepo(t, "internal/booking/app/service.go", sample)
	var seen []string
	if _, err := Run(root, map[string]map[int]bool{"internal/booking/app/service.go": {4: true}},
		func(dir string) (bool, error) { seen = append(seen, dir); return true, nil }); err != nil {
		t.Fatal(err)
	}
	for _, d := range seen {
		if d != "internal/booking/app" {
			t.Errorf("runner got pkgDir %q, want %q", d, "internal/booking/app")
		}
	}
	if len(seen) != 2 {
		t.Errorf("runner called %d times, want 2 (one per mutant)", len(seen))
	}
}

